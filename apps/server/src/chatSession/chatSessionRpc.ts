export const admitChatRpc = (
  method: string,
  payload: unknown,
  access: ChatSessionAccess,
): Effect.Effect<boolean> =>
  Object.hasOwn(CHAT_SESSION_RPC, method)
    ? CHAT_SESSION_RPC[method as WsRpcMethod](payload, access)
    : Effect.succeed(false);
